function initCardEffects() {
  if (matchMedia('(pointer: coarse)').matches || matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  document.querySelectorAll('[data-tilt]').forEach(card => {
    const max = Number(card.dataset.tiltMax || 6);
    card.addEventListener('mousemove', e => {
      const r = card.getBoundingClientRect();
      const x = (e.clientX-r.left)/r.width-.5;
      const y = (e.clientY-r.top)/r.height-.5;
      card.style.transform = `perspective(900px) rotateX(${-y*max}deg) rotateY(${x*max}deg) translateY(-3px)`;
      card.style.setProperty('--mx', `${(x+.5)*100}%`); card.style.setProperty('--my', `${(y+.5)*100}%`);
    });
    card.addEventListener('mouseleave', () => card.style.transform = '');
  });
  document.querySelectorAll('.magnetic').forEach(el => {
    el.addEventListener('mousemove', e => {
      const r = el.getBoundingClientRect();
      el.style.transform = `translate(${(e.clientX-r.left-r.width/2)*.12}px,${(e.clientY-r.top-r.height/2)*.12}px)`;
    });
    el.addEventListener('mouseleave', () => el.style.transform = '');
  });
  const glow = document.querySelector('.cursor-glow');
  addEventListener('pointermove', e => { if (glow) { glow.style.left=e.clientX+'px'; glow.style.top=e.clientY+'px'; } }, { passive:true });
}

function initParallax() {
  if (matchMedia('(prefers-reduced-motion: reduce)').matches || matchMedia('(pointer: coarse)').matches) return;
  const items = document.querySelectorAll('[data-parallax]');
  addEventListener('mousemove', e => {
    const x = e.clientX - innerWidth/2, y = e.clientY - innerHeight/2;
    items.forEach(el => { const amount = Number(el.dataset.parallax || .02); el.style.transform = `translate3d(${x*amount}px,${y*amount}px,0)`; });
  }, { passive:true });
}

function initNetworkCanvas() {
  const canvas = document.getElementById('networkCanvas');
  if (!canvas || matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  const ctx = canvas.getContext('2d');
  let width=0,height=0,dpr=1,nodes=[],mouse={x:-9999,y:-9999};
  function resize() {
    const rect=canvas.getBoundingClientRect(); width=rect.width; height=rect.height; dpr=Math.min(devicePixelRatio||1,2);
    canvas.width=width*dpr; canvas.height=height*dpr; ctx.setTransform(dpr,0,0,dpr,0,0);
    const count=Math.max(28,Math.min(72,Math.round(width*height/18000)));
    nodes=Array.from({length:count},()=>({x:Math.random()*width,y:Math.random()*height,vx:(Math.random()-.5)*.22,vy:(Math.random()-.5)*.22,r:Math.random()*1.6+.6}));
  }
  function frame() {
    ctx.clearRect(0,0,width,height);
    nodes.forEach(n=>{n.x+=n.vx;n.y+=n.vy;if(n.x<0||n.x>width)n.vx*=-1;if(n.y<0||n.y>height)n.vy*=-1;});
    for(let i=0;i<nodes.length;i++){
      const a=nodes[i];
      for(let j=i+1;j<nodes.length;j++){const b=nodes[j],dx=a.x-b.x,dy=a.y-b.y,d=Math.hypot(dx,dy);if(d<125){ctx.strokeStyle=`rgba(96,165,250,${(1-d/125)*.16})`;ctx.lineWidth=.7;ctx.beginPath();ctx.moveTo(a.x,a.y);ctx.lineTo(b.x,b.y);ctx.stroke();}}
      const md=Math.hypot(a.x-mouse.x,a.y-mouse.y);if(md<150){ctx.strokeStyle=`rgba(244,200,75,${(1-md/150)*.25})`;ctx.beginPath();ctx.moveTo(a.x,a.y);ctx.lineTo(mouse.x,mouse.y);ctx.stroke();}
      ctx.fillStyle=i%9===0?'rgba(244,200,75,.75)':'rgba(147,197,253,.55)';ctx.beginPath();ctx.arc(a.x,a.y,a.r,0,Math.PI*2);ctx.fill();
    }
    requestAnimationFrame(frame);
  }
  canvas.addEventListener('pointermove',e=>{const r=canvas.getBoundingClientRect();mouse.x=e.clientX-r.left;mouse.y=e.clientY-r.top;});
  canvas.addEventListener('pointerleave',()=>mouse={x:-9999,y:-9999});
  addEventListener('resize',resize);resize();frame();
}

